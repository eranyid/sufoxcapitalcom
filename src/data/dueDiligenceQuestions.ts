export type DDStatus = 'not_started' | 'in_progress' | 'completed' | 'flagged' | 'na';

export interface DDCheckItem {
  id: string;
  label: string;
  status: DDStatus;
  notes: string;
  assignee: string;
  dueDate: string;
  flag?: string;
}

export interface DDWorkstream {
  id: string;
  title: string;
  icon: any;
  description: string;
  items: DDCheckItem[];
}

function makeItem(id: string, label: string): DDCheckItem {
  return { id, label, status: 'not_started', notes: '', assignee: '', dueDate: '' };
}

